import re

from app.corpus.models import Clause

KEYWORDS = [
    "minimum", "maximum", "not less than", "not exceed", "width", "height", "area",
    "setback", "stair", "door", "fire", "ramp", "parking",
]
NUMBER_WITH_UNIT = re.compile(
    r"\b\d+(?:\.\d+)?\s*(?:sq\.?\s?m(?:t|tr)?s?\b|sqm\b|mm\b|cm\b|m\b|metres?\b|meters?\b)", re.IGNORECASE
)
IDS_LANGUAGE = re.compile(
    r"fire[- ]?(?:rating|resistance|resistant)|non[- ]?combustible|material|shall be provided|provided with",
    re.IGNORECASE,
)
MAX_REVIEWABLE_CHARS = 5000


def propose_tier(text: str) -> str:
    if NUMBER_WITH_UNIT.search(text):
        return "geometric"
    if IDS_LANGUAGE.search(text):
        return "ids"
    return "unclassified"


def score(text: str) -> int:
    lower = text.lower()
    keyword_hits = sum(1 for k in KEYWORDS if k in lower)
    unit_hits = min(len(NUMBER_WITH_UNIT.findall(text)), 5)
    return keyword_hits + 2 * unit_hits


def suggest(clauses: list[Clause], limit: int = 80) -> list[tuple[Clause, int, str]]:
    """Rank reviewable clauses by quantitative language. Plain keyword heuristic, no LLM.

    Unit-bearing clauses outscore everything else, so a quarter of the slots is reserved for
    the best "ids" proposals; otherwise the shortlist would contain no ids candidates at all.
    """
    ranked = [
        (c, score(c.text), propose_tier(c.text))
        for c in clauses
        if len(c.text) <= MAX_REVIEWABLE_CHARS
    ]
    ranked = [r for r in ranked if r[1] > 0]
    ranked.sort(key=lambda r: (-r[1], r[0].page, r[0].id))
    ids_picks = [r for r in ranked if r[2] == "ids"][: limit // 4]
    rest = [r for r in ranked if r not in ids_picks][: limit - len(ids_picks)]
    return sorted(ids_picks + rest, key=lambda r: (-r[1], r[0].page, r[0].id))


def render_markdown(ranked: list[tuple[Clause, int, str]], skipped: list[Clause]) -> str:
    out = [
        "# MBBL 2016 corpus candidates (keyword heuristic, needs human review)",
        "",
        "Generated by `python -m app.corpus.cli suggest`. Plain keyword scoring, no LLM. "
        "Proposed tiers are guesses: numbers with units -> geometric; presence/rating/material "
        "language -> ids. Nothing here is selected; every clause stays `candidate` until marked.",
        "",
        "| # | clause id | page | score | proposed tier | text (first 200 chars) |",
        "|---|---|---|---|---|---|",
    ]
    for i, (c, s, tier) in enumerate(ranked, start=1):
        snippet = " ".join(c.text.split())[:200].replace("|", "\\|")
        out.append(f"| {i} | {c.id} | {c.page} | {s} | {tier} | {snippet} |")
    if skipped:
        out += [
            "",
            f"Skipped (longer than {MAX_REVIEWABLE_CHARS} chars, likely merged tables or lists): "
            + ", ".join(f"{c.id} (p{c.page}, {len(c.text)} chars)" for c in skipped),
        ]
    return "\n".join(out) + "\n"
