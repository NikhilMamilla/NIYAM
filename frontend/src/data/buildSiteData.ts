// Node-only: reads the committed result and documentation files and returns the site data object.
// Run with `npm run site-data` (writes src/data/site-data.json). Never imported by the web app itself.
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { caseStudy, idsSpecifications, markdownTable, parseCsv, runView, type Results } from "./siteData.ts";

export const RUNS = {
  headline: "20261118T140452Z-5b7edb",
  pilot: "20261118T133025Z-4c4519",
  telangana: "20261118T180916Z-4b9c93",
} as const;

const SOURCE_LABEL: Record<string, string> = {
  MBBL2016: "MoHUA Model Building Bye-Laws 2016",
  TGBR2012: "Telangana Building Rules 2012 (G.O.Ms.No.168, original text, amendments not applied)",
};

const safeName = (unitId: string) => unitId.replace(/[.#]/g, "_");

export function buildSiteData(root: string) {
  const read = (...p: string[]) => readFileSync(join(root, ...p), "utf-8");
  const results = (run: string) => JSON.parse(read("eval", "results", run, "results.json")) as Results;

  // units: the review sheet lists every unit with its source, tier and duplicate tag; templates come from the specs
  const sheet = parseCsv(read("docs", "review", "review-sheet.csv"));
  const specs = new Set(readdirSync(join(root, "rules", "specs")));
  const units = sheet.map((r) => {
    const spec = `${safeName(r.unit_id!)}.yaml`;
    const template = specs.has(spec) ? read("rules", "specs", spec).match(/^template:\s*(\S+)/m)?.[1] ?? "unknown" : "hand-written";
    return {
      id: r.unit_id!, source: r.unit_id!.split("-")[0]!, tier: r.tier!, template, duplicateOf: r.duplicate_of || null,
      readingDependent: r.reading_dependent || null, text: r.unit_text!, page: Number(r.page),
    };
  });
  const duplicates = new Set(units.filter((u) => u.duplicateOf).map((u) => u.id));
  const count = (key: (u: (typeof units)[number]) => string) => {
    const out: Record<string, number> = {};
    for (const u of units) out[key(u)] = (out[key(u)] ?? 0) + 1;
    return out;
  };

  const readme = read("README.md");
  const clauses = (label: string) => Number(readme.match(new RegExp(`${label}[^|\\n]*?(\\d+) clauses`))?.[1] ?? NaN);
  const realModels = read("docs", "real-models.md");
  const gatePath = join(root, "docs", "examples", "gate-rejection.json");
  const telangana = results(RUNS.telangana);

  return {
    generated: { note: "Generated by `npm run site-data` from committed files; do not edit by hand.",
      sources: ["eval/results/*/results.json", "docs/review/review-sheet.csv", "rules/specs/*.yaml", "README.md",
        "docs/real-models.md", "docs/readiness/niyam-data-readiness.ids", "docs/examples/gate-rejection.json",
        "backend/app/corpus/extract_tgbr.py"] },
    sources: SOURCE_LABEL,
    corpus: { MBBL2016: clauses("Corpus: MBBL 2016"), TGBR2012: clauses("Corpus: Telangana") },
    units: {
      total: units.length, distinct: units.length - duplicates.size, duplicates: [...duplicates].sort(),
      bySource: count((u) => u.source), byTier: count((u) => `${u.source}/${u.tier}`), byTemplate: count((u) => `${u.source}/${u.template}`),
      readingDependent: units.filter((u) => u.readingDependent).map((u) => ({ id: u.id, note: u.readingDependent })),
      list: units,
    },
    headline: runView(results(RUNS.headline), duplicates),
    pilot: runView(results(RUNS.pilot), duplicates),
    telangana: { provenance: runView(telangana, duplicates).provenance, unitsInRun: new Set(telangana.items.map((i) => i.unit_id)).size,
      items: telangana.items.length, caseStudy: caseStudy(telangana) },
    gateExample: existsSync(gatePath) ? JSON.parse(readFileSync(gatePath, "utf-8")) : null,
    realModels: {
      files: markdownTable(realModels, "## What we tried"),
      audit: markdownTable(realModels, "## Audit results"),
      readiness: markdownTable(realModels, "## What to add to your model before submitting"),
    },
    readiness: idsSpecifications(read("docs", "readiness", "niyam-data-readiness.ids")),
    telanganaSegmenterLines: read("backend", "app", "corpus", "extract_tgbr.py").split(/\r?\n/).filter((l) => l.trim()).length,
  };
}

export type SiteData = ReturnType<typeof buildSiteData>;
